  function normalizeLocale(value) {
    const raw = String(value || "").trim().toLowerCase().replace("_", "-");
    if (raw === "ru" || raw.startsWith("ru-")) return "ru";
    if (raw === "en" || raw.startsWith("en-")) return "en";
    return "en";
  }

  function interpolate(value, params = {}) {
    return String(value || "").replace(/\{([A-Za-z0-9_]+)\}/g, (_match, name) =>
      Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : ""
    );
  }

  function resolveLocale({ storedLocale = null, systemLocale = null } = {}) {
    return storedLocale ? normalizeLocale(storedLocale) : normalizeLocale(systemLocale);
  }

  class DesktopI18n {
    constructor({ storage = globalThis.localStorage, systemLocale = globalThis.navigator?.language } = {}) {
      this.storage = storage || null;
      let storedLocale = null;
      try { storedLocale = this.storage?.getItem?.(STORAGE_KEY) || null; } catch (_) {}
      this.locale = resolveLocale({ storedLocale, systemLocale });
      this.listeners = new Set();
    }

    t(key, params = {}, fallback = "") {
      const english = CATALOGS.en[key];
      const localized = CATALOGS[this.locale]?.[key];
      const value = localized ?? english ?? fallback;
      return interpolate(value, params);
    }

    setLocale(locale) {
      const next = normalizeLocale(locale);
      this.locale = next;
      try { this.storage?.setItem?.(STORAGE_KEY, next); } catch (_) {}
      for (const listener of [...this.listeners]) {
        try { listener(next); } catch (_) {}
      }
      return next;
    }

    subscribe(listener) {
      if (typeof listener !== "function") return () => {};
      this.listeners.add(listener);
      return () => this.listeners.delete(listener);
    }

    apply(documentRoot = globalThis.document) {
      if (!documentRoot?.querySelectorAll) return;
      if (documentRoot.documentElement) documentRoot.documentElement.lang = this.locale;
      for (const element of documentRoot.querySelectorAll("[data-i18n]")) {
        const key = element.getAttribute("data-i18n");
        const value = this.t(key);
        if (value) element.textContent = value;
      }
    }
  }

  root.DesktopI18n = DesktopI18n;
  root.DesktopI18nCatalogs = CATALOGS;
  if (typeof module !== "undefined" && module.exports) module.exports = {
    DesktopI18n,
    CATALOGS,
    STORAGE_KEY,
    normalizeLocale,
    resolveLocale,
    interpolate
  };
